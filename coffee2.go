var resp = []byte(
    "HTTP/1.1 418 I'm a teapot\r\n" +
		"Content-Length: 0\r\n" +
		"Cache-Control: public, max-age=315360000, immutable\r\n" +
		"\r\n")

func serve(l net.Listener) {
	for {
		c, err := l.Accept()
		if err != nil {
			continue
		}

		go func(conn net.Conn) {
			conn.Write(resp)
			conn.Close()
		}(c)
	}
}

func main() {
	cert, err := tls.X509KeyPair([]byte(certPEM), []byte(keyPEM))
	if err != nil {
		log.Fatal(err)
	}

	l80, err := net.Listen("tcp", ":80")
	if err != nil {
		log.Fatal(err)
	}

	tlsCfg := &tls.Config{
		Certificates: []tls.Certificate{cert},
	}

	l443, err := net.Listen("tcp", ":443")
	if err != nil {
		log.Fatal(err)
	}

	go serve(l80)
	go serve(tls.NewListener(l443, tlsCfg))

	select {}
}
